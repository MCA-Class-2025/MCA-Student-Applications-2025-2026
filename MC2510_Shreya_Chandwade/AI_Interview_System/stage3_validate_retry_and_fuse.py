import pandas as pd
import requests
import time
import re
from difflib import SequenceMatcher
from pathlib import Path
from datetime import datetime

BASE = Path(".")
FUSED_FILE = BASE / "fused_interview_dataset_clean.csv"
API_FILE = BASE / "stackoverflow_api_results.csv"
OUTPUT_FILE = BASE / "final_api_enriched_interview_dataset.csv"
VALIDATION_FILE = BASE / "stage3_api_validation_report.csv"
ERROR_FILE = BASE / "stage3_api_retry_results.csv"

API_URL = "https://api.stackexchange.com/2.3/search/advanced"

# -----------------------------
# Helpers
# -----------------------------
STOPWORDS = {
    "what","is","are","the","a","an","of","to","in","on","for","and","or",
    "how","does","do","can","you","explain","describe","would","with","from",
    "this","that","it","be","its","their","your","as","by","about","use",
    "used","using","difference","between","concept","purpose","role"
}

def normalize(text):
    text = "" if pd.isna(text) else str(text).lower()
    text = re.sub(r"[^a-z0-9+#.]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()

def tokens(text):
    return {x for x in normalize(text).split() if x not in STOPWORDS and len(x) > 1}

def jaccard(a, b):
    A, B = tokens(a), tokens(b)
    if not A or not B:
        return 0.0
    return len(A & B) / len(A | B)

def similarity(question, title):
    q, t = normalize(question), normalize(title)
    seq = SequenceMatcher(None, q, t).ratio() if q and t else 0.0
    jac = jaccard(q, t)
    # Lexical overlap is more useful here than Stack Overflow vote score.
    return round(0.55 * jac + 0.45 * seq, 4)

def classify_match(row):
    if row["api_match_status"] not in {"MATCHED", "RETRY_MATCHED"}:
        return "NO_MATCH_OR_ERROR"
    s = row["calculated_text_similarity"]
    if s >= 0.55:
        return "STRONG_MATCH"
    if s >= 0.35:
        return "REVIEW_MATCH"
    return "WEAK_MATCH"

# -----------------------------
# Load
# -----------------------------
if not FUSED_FILE.exists():
    raise FileNotFoundError(f"Missing {FUSED_FILE}")
if not API_FILE.exists():
    raise FileNotFoundError(
        "Missing stackoverflow_api_results.csv. Copy the CSV generated by your API run "
        "into this project folder and run this script again."
    )

fused = pd.read_csv(FUSED_FILE)
api = pd.read_csv(API_FILE)

# Keep one row per original master_row_id.
fused["master_row_id"] = fused["master_row_id"].astype(str)
api["master_row_id"] = api["master_row_id"].astype(str)

# -----------------------------
# STAGE 3A: API validation
# -----------------------------
required_api_cols = [
    "master_row_id", "question", "stackoverflow_question_id",
    "stackoverflow_title", "stackoverflow_tags", "stackoverflow_score",
    "stackoverflow_answer_count", "stackoverflow_is_answered",
    "stackoverflow_view_count", "stackoverflow_accepted_answer",
    "stackoverflow_link", "api_match_status", "api_match_score",
    "api_retrieved_date"
]
missing_cols = [c for c in required_api_cols if c not in api.columns]
if missing_cols:
    raise ValueError(f"API file is missing columns: {missing_cols}")

api["calculated_text_similarity"] = api.apply(
    lambda r: similarity(r["question"], r["stackoverflow_title"]), axis=1
)
api["match_quality"] = api.apply(classify_match, axis=1)

# Duplicate API IDs: same Stack Overflow question returned for multiple interview questions.
api["duplicate_stackoverflow_id"] = api["stackoverflow_question_id"].duplicated(
    keep=False
) & api["stackoverflow_question_id"].notna()

# Basic API field completeness
api["api_record_complete"] = (
    api["stackoverflow_question_id"].notna() &
    api["stackoverflow_title"].notna() &
    api["stackoverflow_link"].notna()
)

validation_summary = pd.DataFrame({
    "Metric": [
        "API result rows",
        "MATCHED",
        "NO_MATCH",
        "ERROR",
        "Strong text matches",
        "Review matches",
        "Weak matches",
        "Retry-matched rows",
        "Retry-no-match rows",
        "Matched rows with complete core API fields",
        "Rows sharing a duplicate Stack Overflow question ID"
    ],
    "Value": [
        len(api),
        int((api["api_match_status"] == "MATCHED").sum()),
        int((api["api_match_status"] == "NO_MATCH").sum()),
        int((api["api_match_status"] == "ERROR").sum()),
        int((api["match_quality"] == "STRONG_MATCH").sum()),
        int((api["match_quality"] == "REVIEW_MATCH").sum()),
        int((api["match_quality"] == "WEAK_MATCH").sum()),
        int((api["api_match_status"] == "RETRY_MATCHED").sum()),
        int((api["api_match_status"] == "RETRY_NO_MATCH").sum()),
        int((api["api_match_status"].isin(["MATCHED", "RETRY_MATCHED"]) & api["api_record_complete"]).sum()),
        int(api["duplicate_stackoverflow_id"].sum())
    ]
})
validation_summary.to_csv(VALIDATION_FILE, index=False)

# -----------------------------
# STAGE 3C: retry only errors
# -----------------------------
errors = api[api["api_match_status"] == "ERROR"].copy()
retry_rows = []

def retry_query(question, attempts=3):
    # Avoid sending the exact long sentence; use a compact query.
    q = normalize(question)
    q = " ".join(q.split()[:12])
    for attempt in range(attempts):
        try:
            params = {
                "site": "stackoverflow",
                "q": q,
                "sort": "relevance",
                "order": "desc",
                "pagesize": 5
            }
            r = requests.get(API_URL, params=params, timeout=20)
            if r.status_code == 429:
                wait = min(60 * (2 ** attempt), 300)
                print(f"429 throttled; waiting {wait}s")
                time.sleep(wait)
                continue
            r.raise_for_status()
            payload = r.json()
            if "backoff" in payload:
                wait = int(payload["backoff"])
                print(f"API backoff={wait}s")
                time.sleep(wait)
                continue
            items = payload.get("items", [])
            if not items:
                return None
            return items[0]
        except Exception as exc:
            if attempt == attempts - 1:
                print("Retry failed:", exc)
                return None
            time.sleep(10 * (attempt + 1))
    return None

if len(errors):
    print(f"Retrying ONLY {len(errors)} ERROR rows...")
    for _, row in errors.iterrows():
        best = retry_query(row["question"])
        if best:
            retry_rows.append({
                "master_row_id": row["master_row_id"],
                "question": row["question"],
                "stackoverflow_question_id": best.get("question_id"),
                "stackoverflow_title": best.get("title"),
                "stackoverflow_tags": ", ".join(best.get("tags", [])),
                "stackoverflow_score": best.get("score", 0),
                "stackoverflow_answer_count": best.get("answer_count", 0),
                "stackoverflow_is_answered": best.get("is_answered", False),
                "stackoverflow_view_count": best.get("view_count", 0),
                "stackoverflow_accepted_answer": best.get("accepted_answer_id"),
                "stackoverflow_link": best.get("link"),
                "api_match_status": "RETRY_MATCHED",
                "api_match_score": best.get("score", 0),
                "api_retrieved_date": datetime.now().date()
            })
        else:
            retry_rows.append({
                "master_row_id": row["master_row_id"],
                "question": row["question"],
                "stackoverflow_question_id": None,
                "stackoverflow_title": None,
                "stackoverflow_tags": None,
                "stackoverflow_score": None,
                "stackoverflow_answer_count": None,
                "stackoverflow_is_answered": None,
                "stackoverflow_view_count": None,
                "stackoverflow_accepted_answer": None,
                "stackoverflow_link": None,
                "api_match_status": "RETRY_NO_MATCH",
                "api_match_score": 0,
                "api_retrieved_date": datetime.now().date()
            })
        # Deliberate pause to avoid rapid requests.
        time.sleep(2)

retry_df = pd.DataFrame(retry_rows)
retry_df.to_csv(ERROR_FILE, index=False)

# -----------------------------
# STAGE 4: final fusion
# -----------------------------
# Do not enrich weak matches. Strong/review matches can be retained with explicit quality.
# NO_MATCH/ERROR remain as API status fields.
if len(retry_df):
    api = api[api["api_match_status"] != "ERROR"].copy()
    api = pd.concat([api, retry_df], ignore_index=True)

api["calculated_text_similarity"] = api.apply(
    lambda r: similarity(r["question"], r["stackoverflow_title"]), axis=1
)
api["match_quality"] = api.apply(classify_match, axis=1)

# Rename API columns so the original dataset remains untouched and provenance is clear.
api_cols = [
    "master_row_id", "stackoverflow_question_id", "stackoverflow_title",
    "stackoverflow_tags", "stackoverflow_score", "stackoverflow_answer_count",
    "stackoverflow_is_answered", "stackoverflow_view_count",
    "stackoverflow_accepted_answer", "stackoverflow_link",
    "api_match_status", "api_match_score", "api_retrieved_date",
    "calculated_text_similarity", "match_quality"
]

api_final = api[api_cols].copy()

# Prevent accidental row multiplication.
api_final = api_final.sort_values(
    ["master_row_id", "calculated_text_similarity"],
    ascending=[True, False]
).drop_duplicates("master_row_id", keep="first")

final = fused.merge(
    api_final,
    on="master_row_id",
    how="left",
    validate="one_to_one"
)

final.to_csv(OUTPUT_FILE, index=False)

print("\n=== STAGE 3A/3B/3C/4 COMPLETE ===")
print("Original rows:", len(fused))
print("Final rows:", len(final))
print("Final columns:", len(final.columns))
print("API rows used:", len(api_final))
print("Output:", OUTPUT_FILE)
